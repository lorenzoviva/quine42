// Gli effetti del Cantiere 3 e la nuova Morte, scritti a mano. Il seme sceglie fra segni nascosti (T U V P M): ogni ascolto è un'istanza.
// Il modo è sempre lo stesso: segni su più altezze o più passi, `<one … steps="n">` ne accende alcuni, `<all>` spegne gli altri.

const COLORS = `  <color symbol="N" value="38bdf8" name="Nota" glow="True"/>
  <color symbol="S" value="0284c7" name="Sustain" alpha="0.85"/>
  <color symbol="A" value="f43f5e" name="Accento" glow="True"/>
  <color symbol="G" value="818cf8" name="Ghost" alpha="0.7"/>
  <color symbol="K" value="fbbf24" name="Kick" glow="True"/>
  <color symbol="H" value="fde047" name="Hi-hat" alpha="0.85"/>
  <color symbol="C" value="fb923c" name="Rullante" glow="True"/>
  <color symbol="T" value="ec4899" name="Scelta" hidden="True"/>
  <color symbol="U" value="a855f7" name="Scelta" hidden="True"/>
  <color symbol="V" value="10b981" name="Scelta" hidden="True"/>
  <color symbol="P" value="64748b" name="Scelta" hidden="True"/>
  <color symbol="M" value="14b8a6" name="Scelta" hidden="True"/>`;

/** Un punto: x y z lettera. */
const at = (x, y, z, c) => `  <line at="${x} ${y} ${z}" to="${x} ${y} ${z}" r="0" color="${c}"/>`;
/** Una riga di segni lungo il tempo, da x0 a x1, sulla traccia y e l'altezza z. */
const row = (x0, x1, y, z, c) => `  <line at="${x0} ${y} ${z}" to="${x1} ${y} ${z}" r="0" color="${c}"/>`;
/** Il seme accende `n` segni `c` come `out`; gli altri tacciono. */
const pick = (c, out, n = 1) => `  <one in="${c}" out="${out}" steps="${n}"/>\n  <all in="${c}" out="B"/>`;

function fx({ name, comment, size, sound, tracks, body }) {
  return `<!-- ${comment} -->
<sequence name="${name}" values="BNSAGKHCTUVPM" size="${size}" symmetry="()">
  <sound ${sound}>
${tracks.map(([i, v], y) => `    <track y="${y}" instrument="${i}" volume="${v}"/>`).join('\n')}
  </sound>
${COLORS}

${body.join('\n')}
</sequence>
`;
}

